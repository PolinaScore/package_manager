/**
 * @file metapackage.h
 * @brief Заголовочный файл для класса MetaPackage
 *
 * @details
 * Класс MetaPackage представляет мета-пакет в системе управления пакетами.
 * Наследуется от абстрактного класса Package и реализует поведение пакета,
 * который служит ссылкой или алиасом для другого реального пакета.
 *
 * Мета-пакеты используются для:
 * - Группировки нескольких пакетов под одним именем
 * - Создания ссылок на рекомендуемые версии пакетов
 * - Предоставления альтернативных имен для пакетов
 * - Управления зависимостями высокого уровня
 *
 * @see Package
 * @see VirtualPackage
 * @see MainPackage
 */

#ifndef METAPACKAGE_H
#define METAPACKAGE_H

#include "package.h"
#include "capabilityinterfaces.h"


 /**
  * @class MetaPackage
  * @brief Класс, представляющий мета-пакет (пакет-алиас)
  *
  * @ingroup PackageTypes
  * @ingroup MetaPackages
  *
  * MetaPackage является специальным типом пакета, который не содержит
  * собственных файлов или данных, а служит ссылкой на другой реальный пакет.
  * Это позволяет создавать абстракции над группами пакетов или предоставлять
  * удобные имена для часто используемых комбинаций.
  *
  * @note Мета-пакеты не могут быть установлены напрямую (canBeInstalled() возвращает false)
  * @note Всегда должны ссылаться на существующий реальный пакет
  * @note Поддерживают семантику копирования через метод clone()
  * 
  */
class MetaPackage : public Package, public IRedirectable {
private:
    std::string linkedPackageName;  ///< Имя пакета, на который ссылается мета-пакет

public:
    /**
     * @brief Конструктор MetaPackage
     * @param[in] name Название мета-пакета
     * @param[in] latestVersion Версия (обычно "latest" для мета-пакетов)
     * @param[in] publisher Издатель/поддерживающая организация (опционально)
     *
     * @details
     * Создает объект мета-пакета. Мета-пакеты обычно имеют версию "latest",
     * так как они ссылаются на текущие версии реальных пакетов.
     *
     * @throw std::invalid_argument если name пустой
     * @throw std::invalid_argument если name совпадает с именем существующего реального пакета
     *
     * @note По умолчанию версия устанавливается в "latest"
     * @note Мета-пакет изначально не ссылается ни на какой пакет (пустая ссылка)
     *
     * @complexity O(1)
     */
    MetaPackage(const std::string& name,
        const std::string& latestVersion = "latest",
        const std::string& publisher = "");

    /**
     * @brief Получает тип пакета
     * @return PackageType::Meta
     *
     * @details
     * Возвращает тип пакета, указывающий что это мета-пакет.
     * Используется для проверки типа во время выполнения и для логирования.
     *
     * @note Переопределяет виртуальный метод Package::getType()
     * @note Гарантированно возвращает PackageType::Meta
     *
     * @complexity O(1)
     */
    PackageType getType() const override;

    /**
     * @brief Получает строковое представление типа пакета
     * @return Строку "Meta"
     *
     * @details
     * Возвращает человекочитаемое название типа пакета.
     * Используется для отображения в пользовательском интерфейсе и логирования.
     *
     * @note Переопределяет виртуальный метод Package::getTypeName()
     * @note Всегда возвращает "Meta" для объектов MetaPackage
     *
     * @complexity O(1)
     */
    std::string getTypeName() const override;

    /**
     * @brief Проверяет, может ли пакет быть установлен
     * @return Всегда false для мета-пакетов
     *
     * @details
     * Мета-пакеты не могут быть установлены напрямую, так как они представляют
     * собой только ссылки на реальные пакеты. При попытке установки мета-пакета
     * система должна установить связанный с ним реальный пакет.
     *
     * @note Переопределяет виртуальный метод Package::canBeInstalled()
     * @note Всегда возвращает false для мета-пакетов
     *
     * @complexity O(1)
     */
    bool canBeInstalled() const override;

    /**
     * @brief Создает глубокую копию объекта
     * @return Указатель на новый объект MetaPackage
     *
     * @details
     * Создает полную копию текущего мета-пакета, включая имя связанного пакета.
     * Используется для реализации полиморфного копирования в иерархии Package.
     *
     * @note Переопределяет виртуальный метод Package::clone()
     * @note Реализует идиому виртуального конструктора
     * @note Копия включает все атрибуты оригинального мета-пакета
     *
     * @complexity O(n) где n - сумма длин строк name и linkedPackageName
     * @throw std::bad_alloc если не удалось выделить память
     *
     */
    Package* clone() const override;

    /**
     * @brief Получает имя связанного пакета
     * @return Имя пакета, на который ссылается мета-пакет
     *
     * @details
     * Возвращает имя реального пакета, на который указывает данный мета-пакет.
     * Если мета-пакет не ссылается ни на какой пакет, возвращает пустую строку.
     *
     * @post Не изменяет состояние объекта
     *
     * @complexity O(1)
     */
    std::string getLinkedPackageName() const { return linkedPackageName; }

    /**
     * @brief Устанавливает имя связанного пакета
     * @param[in] name Имя пакета для связи
     *
     * @details
     * Устанавливает или изменяет имя реального пакета, на который ссылается
     * данный мета-пакет. Это позволяет перенаправлять мета-пакет на разные
     * реальные пакеты в зависимости от контекста или версии.
     *
     * @pre name должен быть именем существующего реального пакета
     * @pre name не должен быть пустым
     *
     * @post linkedPackageName установлен в name
     *
     * @throw std::invalid_argument если name пустой
     * @throw std::invalid_argument если name не соответствует существующему пакету
     *
     * @note Мета-пакет может быть перенаправлен в любой момент
     * @note Обычно используется для указания рекомендуемых версий или групп
     *
     * @complexity O(1)
     *
     */
    void setLinkedPackageName(const std::string& name) { linkedPackageName = name; }

    /**
     * @brief Проверяет, ссылается ли мета-пакет на какой-либо пакет
     * @return true если linkedPackageName не пустой, false в противном случае
     *
     * @details
     * Проверяет, установлена ли связь мета-пакета с реальным пакетом.
     * Мета-пакет без установленной связи считается недействительным
     * и не может быть использован в операциях установки/обновления.
     *
     * @post Не изменяет состояние объекта
     *
     * @complexity O(1)
     *
     */
    bool hasLinkedPackage() const { return !linkedPackageName.empty(); }

    /**
     * @brief Получает строковое представление мета-пакета
     * @return Отформатированную строку с информацией о мета-пакете
     *
     * @details
     * Возвращает подробное текстовое представление мета-пакета в формате:
     * "MetaPackage [name=... version=... publisher=... linkedTo=...]"
     *
     * Используется для:
     * - Логирования и отладки
     * - Отображения информации в пользовательском интерфейсе
     * - Сериализации/десериализации
     *
     * @note Переопределяет виртуальный метод Package::toString()
     * @note Формат строки гарантированно совместим с parseFromString()
     *
     * @complexity O(n) где n - сумма длин всех строковых полей
     *
     */
    std::string toString() const override;
};

#endif // METAPACKAGE_H